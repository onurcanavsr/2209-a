"""Özeti düzenli, metni seçilebilir bir PDF'e dönüştürür (reportlab).

Özet, `summarize.py` istemlerinin ürettiği SINIRLI Markdown'dır: `## başlık`, `- madde`, `**kalın**`, paragraf.
Ekrandaki ayrıştırma (`web/lib/ozetAgaci.ts`) ile aynı kurallar kullanılır; böylece PDF'te görülen sıra ekrandakiyle aynıdır.

- Metin vektör olarak yazılır (görüntü değil): kopyalanınca satırlar ve maddeler düzenli çıkar, aranabilir.
- Türkçe karakterler (ı, İ, ş, ğ ...) için standart PDF yazı tipleri yetmez; DejaVu Sans gömülür. Docker imajında
  `fonts-dejavu-core` kuruludur (api/Dockerfile). Başka bir yerde çalıştırırsanız `PDF_FONT_DIR` ile klasörü verin.
- Senkron ve CPU kullanır: çağıran thread pool içinde çalıştırmalıdır.
"""
import io
import os
import re
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer

BRAND = "Sentez"
FONT = "DejaVuSans"
FONT_BOLD = "DejaVuSans-Bold"
FONT_DIRS = (
    "/usr/share/fonts/truetype/dejavu",   # Debian / Ubuntu (fonts-dejavu-core)
    "/usr/share/fonts/dejavu",            # Fedora / Alpine
    "/usr/share/fonts/TTF",               # Arch
    "/Library/Fonts",                     # macOS
    "C:/Windows/Fonts",                   # Windows (DejaVu elle kurulmuşsa)
)
TR_TZ = timezone(timedelta(hours=3))      # Türkiye 2016'dan beri sabit UTC+3

LEVEL_NAME = {
    "tr": {"short": "Kısa", "medium": "Orta", "detailed": "Ayrıntılı"},
    "en": {"short": "Short", "medium": "Medium", "detailed": "Detailed"},
}
MONTHS = {
    "tr": ["Ocak", "Şubat", "Mart", "Nisan", "Mayıs", "Haziran", "Temmuz", "Ağustos", "Eylül", "Ekim", "Kasım", "Aralık"],
    "en": ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
           "November", "December"],
}
TEXT = {
    "tr": {"summary": "Özet", "page": "Sayfa", "of": "/", "prepared": "Hazırlanma tarihi",
           "disclaimer": "Bu özet yapay zekâ tarafından üretilmiştir ve hata içerebilir; önemli konularda asıl metni kontrol edin.",
           "word": "belge"},
    "en": {"summary": "Summary", "page": "Page", "of": "/", "prepared": "Prepared on",
           "disclaimer": "This summary was generated by AI and may contain errors; check the original text for important matters.",
           "word": "document"},
}
KNOWN_EXT = (".pdf", ".docx", ".pptx")


class PdfFontError(RuntimeError):
    """Gerekli yazı tipi bulunamadı (sunucu yapılandırması)."""


# ---------------------------------------------------------------------------------------------
# yazı tipi
_fonts_ready = False


def _find_font(name: str, extra_dir: str = "") -> str | None:
    for d in ([extra_dir] if extra_dir else []) + list(FONT_DIRS):
        p = os.path.join(d, name)
        if d and os.path.isfile(p):
            return p
    return None


def ensure_fonts(extra_dir: str = "") -> None:
    global _fonts_ready
    if _fonts_ready:
        return
    reg = _find_font("DejaVuSans.ttf", extra_dir)
    bold = _find_font("DejaVuSans-Bold.ttf", extra_dir)
    if not reg or not bold:
        raise PdfFontError("DejaVu Sans yazı tipi bulunamadı (fonts-dejavu-core kurulu olmalı veya PDF_FONT_DIR verilmeli)")
    pdfmetrics.registerFont(TTFont(FONT, reg))
    pdfmetrics.registerFont(TTFont(FONT_BOLD, bold))
    # <b> işaretini kalın yüze bağlar; italik kullanılmıyor, eğik istenirse düz yüze düşer
    pdfmetrics.registerFontFamily(FONT, normal=FONT, bold=FONT_BOLD, italic=FONT, boldItalic=FONT_BOLD)
    _fonts_ready = True


# ---------------------------------------------------------------------------------------------
# Markdown ayrıştırma (ozetAgaci.ts ile aynı kurallar)
@dataclass
class Blok:
    tur: str                 # "baslik" | "liste" | "paragraf"
    metin: str = ""          # başlık / paragraf
    maddeler: tuple = ()     # liste
    seviye: int = 2          # başlık düzeyi (# sayısı)


_H = re.compile(r"^(#{1,4})\s+(.*)$")
_LI = re.compile(r"^[-*•]\s+(.*)$")


def ayristir(markdown: str) -> list[Blok]:
    bloklar: list[Blok] = []
    liste: list[str] = []
    para: list[str] = []

    def flush_list():
        nonlocal liste
        if liste:
            bloklar.append(Blok("liste", maddeler=tuple(liste)))
            liste = []

    def flush_para():
        nonlocal para
        if para:
            bloklar.append(Blok("paragraf", metin=" ".join(para)))
            para = []

    for raw in (markdown or "").replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        line = raw.strip()
        h, li = _H.match(line), _LI.match(line)
        if h:
            flush_list(); flush_para()
            bloklar.append(Blok("baslik", metin=h.group(2).strip(), seviye=len(h.group(1))))
        elif li:
            flush_para()
            liste.append(li.group(1).strip())
        elif not line:
            flush_list(); flush_para()
        else:
            flush_list()
            para.append(line)
    flush_list(); flush_para()
    return [b for b in bloklar if (b.metin or b.maddeler)]


_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f\u200b-\u200f\u2028\u2029\ufeff]")
_BOLD = re.compile(r"\*\*(.+?)\*\*")


def satir_ici(text: str) -> str:
    """Güvenilmez model çıktısını reportlab işaretlemesine çevirir: önce kaçışlanır, sonra yalnızca **kalın** <b> olur."""
    t = escape(_CTRL.sub("", text or ""))
    t = _BOLD.sub(r"<b>\1</b>", t)
    return t.replace("**", "")      # eşleşmeyen yıldız çiftleri görünmesin


# ---------------------------------------------------------------------------------------------
# stiller
INK = colors.HexColor("#1b1b1b")
ACCENT = colors.HexColor("#1f3a5f")
MUTED = colors.HexColor("#5a5a5a")
RULE = colors.HexColor("#c9d1dc")


def _styles() -> dict[str, ParagraphStyle]:
    base = dict(fontName=FONT, textColor=INK, alignment=TA_LEFT, wordWrap=None, splitLongWords=1)
    return {
        "title": ParagraphStyle("title", **{**base, "fontName": FONT_BOLD, "textColor": ACCENT},
                                fontSize=20, leading=25, spaceAfter=4),
        "meta": ParagraphStyle("meta", **{**base, "textColor": MUTED}, fontSize=9.5, leading=13, spaceAfter=6),
        "h1": ParagraphStyle("h1", **{**base, "fontName": FONT_BOLD, "textColor": ACCENT},
                             fontSize=15, leading=19, spaceBefore=16, spaceAfter=6, keepWithNext=1),
        "h2": ParagraphStyle("h2", **{**base, "fontName": FONT_BOLD, "textColor": ACCENT},
                             fontSize=12.5, leading=16, spaceBefore=13, spaceAfter=5, keepWithNext=1),
        "p": ParagraphStyle("p", **base, fontSize=10.5, leading=16, spaceAfter=7),
        "li": ParagraphStyle("li", **base, fontSize=10.5, leading=16, leftIndent=16, bulletIndent=3,
                             bulletFontName=FONT, spaceAfter=4),
        "note": ParagraphStyle("note", **{**base, "textColor": MUTED}, fontSize=8.5, leading=12, spaceBefore=4),
    }


def _tarih(created_at: str | None, lang: str) -> str:
    dt = None
    if created_at:
        try:
            dt = datetime.fromisoformat(created_at.replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
        except ValueError:
            dt = None
    dt = (dt or datetime.now(timezone.utc)).astimezone(TR_TZ)
    return f"{dt.day} {MONTHS[lang][dt.month - 1]} {dt.year}"


def baslik_adi(title: str | None) -> str:
    """Belge başlığı: yalnızca bilinen dosya uzantısı atılır (YouTube başlığındaki '3.9' gibi noktalar korunur)."""
    t = _CTRL.sub("", (title or "").strip())
    if t.lower().endswith(KNOWN_EXT):
        t = t.rsplit(".", 1)[0]
    return t.strip()


def dosya_adi(title: str | None, lang: str) -> str:
    """İndirilen dosyanın adı: '<belge> - özet.pdf' (Türkçe) / '<belge> - summary.pdf' (İngilizce)."""
    t = TEXT["en" if lang == "en" else "tr"]
    stem = "".join(c for c in baslik_adi(title) if c.isalnum() or c in " -_.")[:80].strip(" .") or t["word"]
    return f"{stem} - {t['summary'].lower() if lang == 'en' else 'özet'}.pdf"


def akis(markdown: str, *, title: str, level: str, lang: str, created_at: str | None = None,
         font_dir: str = "") -> list:
    """Belge içeriği (flowable listesi). Ayrı tutulur ki testler PDF'e çevirmeden de içeriği denetleyebilsin."""
    lang = "en" if lang == "en" else "tr"
    ensure_fonts(font_dir)
    st, tx = _styles(), TEXT[lang]
    out: list = [Paragraph(satir_ici(baslik_adi(title)) or tx["word"], st["title"]),
                 Paragraph(satir_ici(f"{tx['summary']} ({LEVEL_NAME[lang].get(level, level)}) · "
                                     f"{tx['prepared']}: {_tarih(created_at, lang)}"), st["meta"]),
                 HRFlowable(width="100%", thickness=0.8, color=RULE, spaceBefore=2, spaceAfter=6)]
    for b in ayristir(markdown):
        if b.tur == "baslik":
            out.append(Paragraph(satir_ici(b.metin), st["h1"] if b.seviye <= 2 else st["h2"]))
        elif b.tur == "liste":
            out.extend(Paragraph(satir_ici(m), st["li"], bulletText="•") for m in b.maddeler)
            out.append(Spacer(1, 3))
        else:
            out.append(Paragraph(satir_ici(b.metin), st["p"]))
    out.append(HRFlowable(width="100%", thickness=0.5, color=RULE, spaceBefore=10, spaceAfter=4))
    out.append(Paragraph(satir_ici(tx["disclaimer"]), st["note"]))
    return out


def _canvas_factory(lang: str):
    tx = TEXT[lang]

    class _Numbered(canvas.Canvas):
        """İki geçişli sayfa numarası: 'Sayfa 2 / 5' (toplam, tüm sayfalar bilinince yazılır)."""

        def __init__(self, *a, **kw):
            super().__init__(*a, **kw)
            self._pages: list[dict] = []

        def showPage(self):
            self._pages.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            n = len(self._pages)
            for state in self._pages:
                self.__dict__.update(state)
                self.setFont(FONT, 8.5)
                self.setFillColor(MUTED)
                y = 12 * mm
                self.drawString(20 * mm, y, BRAND)
                self.drawRightString(A4[0] - 20 * mm, y, f"{tx['page']} {self._pageNumber} {tx['of']} {n}")
                super().showPage()
            super().save()

    return _Numbered


def ozet_pdf(markdown: str, *, title: str, level: str = "medium", lang: str = "tr",
             created_at: str | None = None, font_dir: str = "") -> bytes:
    """Özetin PDF baytları. Yazı tipi yoksa PdfFontError."""
    lang = "en" if lang == "en" else "tr"
    ensure_fonts(font_dir)
    buf = io.BytesIO()
    name = baslik_adi(title) or TEXT[lang]["word"]
    kw = dict(pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=20 * mm, bottomMargin=22 * mm,
              title=f"{name} - {TEXT[lang]['summary']}", author=BRAND, subject=TEXT[lang]["summary"], creator=BRAND)
    try:
        doc = SimpleDocTemplate(buf, lang=lang, **kw)     # belge dili (ekran okuyucu/Acrobat için); eski sürümde yok
    except TypeError:
        doc = SimpleDocTemplate(buf, **kw)
    doc.build(akis(markdown, title=title, level=level, lang=lang, created_at=created_at, font_dir=font_dir),
              canvasmaker=_canvas_factory(lang))
    return buf.getvalue()
